/**
 * Registry Lookup and Filtering Helpers
 */
export function getCapabilityById(id: string): CapabilityRecord | undefined {
  return CAPABILITY_REGISTRY.find((c) => c.id.toUpperCase() === id.toUpperCase());
}

export function listCapabilities(filter?: {
  domain?: string;
  classification?: CapabilityClassification;
  implementationStatus?: ImplementationStatus;
  activationStatus?: ActivationStatus;
  verificationStatus?: VerificationStatus;
}): CapabilityRecord[] {
  if (!filter) return [...CAPABILITY_REGISTRY];
  return CAPABILITY_REGISTRY.filter((c) => {
    if (filter.domain && c.domain.toLowerCase() !== filter.domain.toLowerCase()) return false;
    if (filter.classification && c.classification !== filter.classification) return false;
    if (filter.implementationStatus && c.implementationStatus !== filter.implementationStatus) return false;
    if (filter.activationStatus && c.activationStatus !== filter.activationStatus) return false;
    if (filter.verificationStatus && c.verificationStatus !== filter.verificationStatus) return false;
    return true;
  });
}

export function getCapabilitiesByClassification(classification: CapabilityClassification): CapabilityRecord[] {
  return CAPABILITY_REGISTRY.filter((c) => c.classification === classification);
}

export function getCapabilitiesByDomain(domain: string): CapabilityRecord[] {
  return CAPABILITY_REGISTRY.filter((c) => c.domain.toLowerCase() === domain.toLowerCase());
}

/**
 * Validates registry completeness and ensures:
 * - Exactly 120 unique records from CAP-001 through CAP-120
 * - Every classification is F, G, or B
 * - Every record has a valid controlling source clause
 * - Every dependency references a valid CAP record
 */
export function validateRegistryIntegrity(): {
  valid: boolean;
  totalCount: number;
  foundationCount: number;
  growthCount: number;
  businessCount: number;
  missingIds: string[];
  duplicateIds: string[];
  brokenDependencies: Array<{ capId: string; missingDep: string }>;
} {
  const seenIds = new Set<string>();
  const duplicateIds: string[] = [];
  const validIds = new Set(CAPABILITY_REGISTRY.map((c) => c.id));
  const missingIds: string[] = [];
  const brokenDependencies: Array<{ capId: string; missingDep: string }> = [];

  let foundationCount = 0;
  let growthCount = 0;
  let businessCount = 0;

  for (let i = 1; i <= 120; i++) {
    const expectedId = `CAP-${String(i).padStart(3, "0")}`;
    if (!validIds.has(expectedId)) {
      missingIds.push(expectedId);
    }
  }

  for (const cap of CAPABILITY_REGISTRY) {
    if (seenIds.has(cap.id)) {
      duplicateIds.push(cap.id);
    }
    seenIds.add(cap.id);

    if (cap.classification === "F") foundationCount++;
    else if (cap.classification === "G") growthCount++;
    else if (cap.classification === "B") businessCount++;

    for (const dep of cap.dependencies) {
      if (!validIds.has(dep)) {
        brokenDependencies.push({ capId: cap.id, missingDep: dep });
      }
    }
  }

  const valid =
    CAPABILITY_REGISTRY.length === 120 &&
    missingIds.length === 0 &&
    duplicateIds.length === 0 &&
    brokenDependencies.length === 0;

  return {
    valid,
    totalCount: CAPABILITY_REGISTRY.length,
    foundationCount,
    growthCount,
    businessCount,
    missingIds,
    duplicateIds,
    brokenDependencies,
  };
}
