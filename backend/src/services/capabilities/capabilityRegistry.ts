/**
 * ForgeStudio Execution Blueprint v2.1 — Point 05: Executable Capability Contract
 * Canonical Capability and Evidence Registry (CAP-001 through CAP-120)
 *
 * Implements the authoritative capability registry preserving:
 * - 120 Original Capability Records (CAP-001 to CAP-120)
 * - Source Classifications:
 *   - F: Universal Foundation (mandatory baseline requirements)
 *   - G: Comprehensive Growth-Platform Capability (in platform engineering scope)
 *   - B: Conditional Business Module (evaluated against business brief)
 * - Five Independent Status Dimensions:
 *   1. Specification Status (UNREVIEWED, DEFINED, AMBIGUOUS, CONFLICTED, APPROVED)
 *   2. Applicability Status (NOT_EVALUATED, APPLICABLE, NOT_APPLICABLE, CONDITION_UNMET, BLOCKED)
 *   3. Implementation Status (NOT_IMPLEMENTED, PARTIAL, IMPLEMENTED, IMPLEMENTATION_BLOCKED)
 *   4. Activation Status (DISABLED, PENDING_ACTIVATION, ACTIVE, DEGRADED, DISABLING, DISABLED_WITH_RETAINED_DATA, BLOCKED)
 *   5. Verification Status (UNVERIFIED, IN_PROGRESS, PASSED, FAILED, STALE, BLOCKED)
 * - Traceable dependencies, routes, entities, jobs, telemetry, and limitations.
 */

export type CapabilityClassification = "F" | "G" | "B";

export type SpecificationStatus =
  | "UNREVIEWED"
  | "DEFINED"
  | "AMBIGUOUS"
  | "CONFLICTED"
  | "APPROVED";

export type ApplicabilityStatus =
  | "NOT_EVALUATED"
  | "APPLICABLE"
  | "NOT_APPLICABLE"
  | "CONDITION_UNMET"
  | "BLOCKED";

export type ImplementationStatus =
  | "NOT_IMPLEMENTED"
  | "PARTIAL"
  | "IMPLEMENTED"
  | "IMPLEMENTATION_BLOCKED";

export type ActivationStatus =
  | "DISABLED"
  | "PENDING_ACTIVATION"
  | "ACTIVE"
  | "DEGRADED"
  | "DISABLING"
  | "DISABLED_WITH_RETAINED_DATA"
  | "BLOCKED";

export type VerificationStatus =
  | "UNVERIFIED"
  | "IN_PROGRESS"
  | "PASSED"
  | "FAILED"
  | "STALE"
  | "BLOCKED";

export interface CapabilityRecord {
  id: string; // e.g. "CAP-001"
  name: string;
  description: string;
  domain: string;
  classification: CapabilityClassification;
  sourceClause: string;
  sourceQualifiers: string[];
  specificationStatus: SpecificationStatus;
  applicabilityStatus: ApplicabilityStatus;
  implementationStatus: ImplementationStatus;
  activationStatus: ActivationStatus;
  verificationStatus: VerificationStatus;
  responsibleOwner: string;
  dependencies: string[];
  publicRoutes: string[];
  adminRoutes: string[];
  services: string[];
  entities: string[];
  authorizationPolicies: string[];
  migrations: string[];
  jobs: string[];
  telemetrySignals: string[];
  testReferences: string[];
  exportDependencies: string[];
  disableExitBehavior: string;
  limitations: string[];
}

