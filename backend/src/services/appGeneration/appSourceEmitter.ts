export interface SourceValidation {
  ok: boolean;
  errors: string[];
  checkedFiles: number;
}

const BUILTINS = new Set(builtinModules);

/**
 * Static checks only: TypeScript syntax (esbuild), relative import resolution, bare imports
 * declared in the package manifest (dependency closure) and JSON structure.
 */
export function validateEmittedSource(files: EmittedFile[]): SourceValidation {
  const errors: string[] = [];
  const paths = new Set(files.map((f) => f.path));
  let checkedFiles = 0;

  const manifestFile = files.find((f) => f.path === `${GENERATED_ROOT}/package.json`);
  let declared = new Set<string>();
  if (!manifestFile) {
    errors.push(`${GENERATED_ROOT}/package.json is missing`);
  } else {
    try {
      const manifest = JSON.parse(manifestFile.content);
      declared = new Set([...Object.keys(manifest.dependencies ?? {}), ...Object.keys(manifest.devDependencies ?? {})]);
    } catch {
      // reported by the JSON check below
    }
  }

  for (const file of files) {
    if (file.path.endsWith(".ts")) {
      checkedFiles++;
      let js: string;
      try {
        js = transformSync(file.content, { loader: "ts", format: "esm", sourcefile: file.path }).code;
      } catch (err: any) {
        const messages = Array.isArray(err?.errors) && err.errors.length > 0
          ? err.errors.map((e: any) => `${e.text}${e.location ? ` (line ${e.location.line})` : ""}`)
          : [String(err?.message || err)];
        for (const m of messages) errors.push(`${file.path}: ${m}`);
        continue;
      }
      // esbuild drops type-only imports, so imports are read from the TypeScript source text as
      // well: every module specifier must resolve to a generated file or a declared dependency.
      const program = parseJs(js, { ecmaVersion: "latest", sourceType: "module" }) as any;
      const specifiers = new Set<string>();
      for (const node of program.body) {
        if (node.type === "ImportDeclaration" || ((node.type === "ExportNamedDeclaration" || node.type === "ExportAllDeclaration") && node.source)) {
          specifiers.add(node.source.value);
        }
      }
      for (const m of file.content.matchAll(/^\s*import\s+type\s[^;]*?from\s+["']([^"']+)["']/gm)) specifiers.add(m[1]);
      for (const spec of specifiers) {
        if (spec.startsWith(".")) {
          const target = path.posix.normalize(path.posix.join(path.posix.dirname(file.path), spec)).replace(/\.js$/, ".ts");
          if (!paths.has(target)) errors.push(`${file.path}: import "${spec}" does not resolve within the generated source`);
          continue;
        }
        const bare = spec.startsWith("node:") ? spec.slice(5) : spec;
        if (BUILTINS.has(bare)) continue;
        const pkg = spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0];
        if (!declared.has(pkg)) errors.push(`${file.path}: import "${spec}" is not a declared dependency`);
      }
    } else if (file.path.endsWith(".json")) {
      checkedFiles++;
      try { JSON.parse(file.content); } catch { errors.push(`${file.path}: invalid JSON`); }
    }
  }
  return { ok: errors.length === 0, errors, checkedFiles };
}
