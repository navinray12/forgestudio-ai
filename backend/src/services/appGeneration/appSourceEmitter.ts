const TOKEN_MODULE = `import crypto from "node:crypto";

/** A verified principal. The tenant comes only from a token signed with APP_AUTH_SECRET. */
export interface Principal {
  sub: string;
  tenantId: string;
  exp: number;
}

const sign = (body: string, secret: string) => crypto.createHmac("sha256", secret).update(body).digest();

export function signToken(principal: Principal, secret: string): string {
  const body = Buffer.from(JSON.stringify(principal)).toString("base64url");
  return \`\${body}.\${sign(body, secret).toString("base64url")}\`;
}

export function verifyToken(token: string, secret: string, now = Date.now()): Principal | null {
  const parts = token.split(".");
  if (parts.length !== 2) return null;
  const [body, signature] = parts;
  const expected = sign(body, secret);
  const given = Buffer.from(signature, "base64url");
  if (given.length !== expected.length || !crypto.timingSafeEqual(given, expected)) return null;
  let claims: Partial<Principal>;
  try {
    claims = JSON.parse(Buffer.from(body, "base64url").toString("utf8"));
  } catch {
    return null;
  }
  if (typeof claims.sub !== "string" || !claims.sub || typeof claims.tenantId !== "string" || !claims.tenantId) return null;
  if (typeof claims.exp !== "number" || claims.exp * 1000 <= now) return null;
  return { sub: claims.sub, tenantId: claims.tenantId, exp: claims.exp };
}
`;

