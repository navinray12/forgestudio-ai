/**
 * Emits application source from a validated AppModel and validates it statically.
 *
 * Generated code is never executed inside the platform process (blueprint §08, FS21-AT-GEN-10):
 * validation is limited to TypeScript syntax checks (esbuild), relative-import resolution within the
 * generated set and structural checks of non-code files.
 */
import path from "node:path";
import { transformSync } from "esbuild";
import { parse as parseJs } from "acorn";
import type { AppModel, AppModelEntity, AppFieldType } from "./appModel.js";
import { resourcePath, tableName } from "./appModel.js";

export const GENERATED_ROOT = "forge-app";
export const GENERATED_MARKER = "@forge-generated";

export interface EmittedFile {
  path: string;
  content: string;
  role: "SCHEMA" | "SERVER" | "VALIDATION" | "CLIENT" | "TEST" | "SPEC" | "DOC";
}

const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const fileBase = (entity: string) => lowerFirst(entity);

const PRISMA_TYPE: Record<AppFieldType, string> = {
  string: "String", text: "String", integer: "Int", number: "Float", boolean: "Boolean", datetime: "DateTime",
};
const TS_TYPE: Record<AppFieldType, string> = {
  string: "string", text: "string", integer: "number", number: "number", boolean: "boolean", datetime: "string",
};

function header(runId: string, commentStart = "//"): string {
  return `${commentStart} ${GENERATED_MARKER} run:${runId} — regenerated by ForgeStudio; edit the application model instead.\n`;
}

function prismaSchema(model: AppModel, runId: string): string {
  const models = model.entities.map((e) => {
    const fields = e.fields
      .map((f) => {
        const type = PRISMA_TYPE[f.type] + (f.required ? "" : "?");
        const attr = f.type === "text" ? " @db.Text" : "";
        return `  ${f.name} ${type}${attr}`;
      })
      .join("\n");
    return `model ${e.name} {
  id        String    @id @default(uuid()) @db.Uuid
  tenantId  String
${fields}
  createdAt DateTime  @default(now())
  updatedAt DateTime  @updatedAt
  deletedAt DateTime?

  @@index([tenantId])
  @@map("${tableName(e.name)}")
}`;
  });
  return `${header(runId)}generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
}

${models.join("\n\n")}
`;
}

function sqlPlan(model: AppModel, runId: string): string {
  const SQL: Record<AppFieldType, string> = {
    string: "VARCHAR(255)", text: "TEXT", integer: "INTEGER", number: "DOUBLE PRECISION", boolean: "BOOLEAN", datetime: "TIMESTAMPTZ",
  };
  const tables = model.entities.map((e) => {
    const cols = e.fields.map((f) => `  "${f.name}" ${SQL[f.type]}${f.required ? " NOT NULL" : ""},`).join("\n");
    const t = tableName(e.name);
    return `CREATE TABLE IF NOT EXISTS "${t}" (
  "id" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  "tenantId" TEXT NOT NULL,
${cols}
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "deletedAt" TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS "idx_${t}_tenant" ON "${t}" ("tenantId");`;
  });
  return `${header(runId, "--")}-- Reviewable schema plan. It is NOT applied automatically to any environment.\n${tables.join("\n\n")}\n`;
}

function validationModule(e: AppModelEntity, runId: string): string {
  const specs = e.fields.map((f) => `  ${f.name}: { type: "${f.type}", required: ${f.required} },`).join("\n");
  const shape = e.fields.map((f) => `  ${f.name}${f.required ? "" : "?"}: ${TS_TYPE[f.type]}${f.required ? "" : " | null"};`).join("\n");
  return `${header(runId)}
export interface ${e.name}Input {
${shape}
}

type FieldType = "string" | "text" | "integer" | "number" | "boolean" | "datetime";
const FIELDS: Record<string, { type: FieldType; required: boolean }> = {
${specs}
};

export type ParseResult<T> = { ok: true; value: T } | { ok: false; errors: string[] };

function checkValue(name: string, type: FieldType, value: unknown): string | null {
  switch (type) {
    case "string": return typeof value === "string" && value.length <= 255 ? null : \`\${name} must be a string of at most 255 characters\`;
    case "text": return typeof value === "string" && value.length <= 10000 ? null : \`\${name} must be a string of at most 10000 characters\`;
    case "integer": return Number.isInteger(value) ? null : \`\${name} must be an integer\`;
    case "number": return typeof value === "number" && Number.isFinite(value) ? null : \`\${name} must be a finite number\`;
    case "boolean": return typeof value === "boolean" ? null : \`\${name} must be a boolean\`;
    case "datetime": return typeof value === "string" && !Number.isNaN(Date.parse(value)) ? null : \`\${name} must be an ISO date-time\`;
  }
}

/** Accepts only declared fields; platform-owned fields such as tenantId are always rejected. */
function parse(input: unknown, partial: boolean): ParseResult<Partial<${e.name}Input>> {
  if (!input || typeof input !== "object" || Array.isArray(input)) return { ok: false, errors: ["Body must be a JSON object"] };
  const errors: string[] = [];
  const value: Record<string, unknown> = {};
  for (const [key, raw] of Object.entries(input as Record<string, unknown>)) {
    const spec = FIELDS[key];
    if (!spec) { errors.push(\`Unknown or read-only field: \${key}\`); continue; }
    if (raw === null && !spec.required) { value[key] = null; continue; }
    const problem = checkValue(key, spec.type, raw);
    if (problem) errors.push(problem);
    else value[key] = raw;
  }
  if (!partial) {
    for (const [key, spec] of Object.entries(FIELDS)) {
      if (spec.required && value[key] === undefined) errors.push(\`\${key} is required\`);
    }
  } else if (Object.keys(value).length === 0 && errors.length === 0) {
    errors.push("No updatable fields supplied");
  }
  return errors.length > 0 ? { ok: false, errors } : { ok: true, value: value as Partial<${e.name}Input> };
}

export const parse${e.name}Create = (input: unknown) => parse(input, false) as ParseResult<${e.name}Input>;
export const parse${e.name}Update = (input: unknown) => parse(input, true);
`;
}

function routesModule(e: AppModelEntity, runId: string): string {
  const accessor = lowerFirst(e.name);
  const base = fileBase(e.name);
  const dateFields = e.fields.filter((f) => f.type === "datetime").map((f) => `"${f.name}"`);
  return `${header(runId)}import { Router } from "express";
import { db } from "./db.js";
import { tenantOf, toDates } from "./http.js";
import { parse${e.name}Create, parse${e.name}Update } from "./${base}.validation.js";

const DATE_FIELDS = [${dateFields.join(", ")}];
export const ${accessor}Router = Router();

${accessor}Router.get("/", async (req, res, next) => {
  try {
    const tenantId = tenantOf(req, res);
    if (!tenantId) return;
    const take = Math.min(Math.max(Number(req.query.limit) || 50, 1), 100);
    const records = await db.${accessor}.findMany({ where: { tenantId, deletedAt: null }, orderBy: { createdAt: "desc" }, take });
    res.json({ data: records });
  } catch (err) { next(err); }
});

${accessor}Router.get("/:id", async (req, res, next) => {
  try {
    const tenantId = tenantOf(req, res);
    if (!tenantId) return;
    const record = await db.${accessor}.findFirst({ where: { id: req.params.id, tenantId, deletedAt: null } });
    if (!record) return void res.status(404).json({ error: "Not found" });
    res.json({ data: record });
  } catch (err) { next(err); }
});

${accessor}Router.post("/", async (req, res, next) => {
  try {
    const tenantId = tenantOf(req, res);
    if (!tenantId) return;
    const parsed = parse${e.name}Create(req.body);
    if (!parsed.ok) return void res.status(422).json({ errors: parsed.errors });
    const record = await db.${accessor}.create({ data: { ...toDates(parsed.value, DATE_FIELDS), tenantId } });
    res.status(201).json({ data: record });
  } catch (err) { next(err); }
});

${accessor}Router.patch("/:id", async (req, res, next) => {
  try {
    const tenantId = tenantOf(req, res);
    if (!tenantId) return;
    const parsed = parse${e.name}Update(req.body);
    if (!parsed.ok) return void res.status(422).json({ errors: parsed.errors });
    const result = await db.${accessor}.updateMany({
      where: { id: req.params.id, tenantId, deletedAt: null },
      data: toDates(parsed.value, DATE_FIELDS),
    });
    if (result.count === 0) return void res.status(404).json({ error: "Not found" });
    res.json({ data: await db.${accessor}.findFirst({ where: { id: req.params.id, tenantId } }) });
  } catch (err) { next(err); }
});

/** Archives (soft-deletes) a record; nothing is permanently deleted by this API. */
${accessor}Router.delete("/:id", async (req, res, next) => {
  try {
    const tenantId = tenantOf(req, res);
    if (!tenantId) return;
    const result = await db.${accessor}.updateMany({
      where: { id: req.params.id, tenantId, deletedAt: null },
      data: { deletedAt: new Date() },
    });
    if (result.count === 0) return void res.status(404).json({ error: "Not found" });
    res.status(204).end();
  } catch (err) { next(err); }
});
`;
}

function httpModule(runId: string): string {
  return `${header(runId)}import type { Request, Response } from "express";

/**
 * The tenant comes only from the authenticated principal that the host application's auth
 * middleware attaches to the request. Requests without one are rejected; there is no default.
 */
export function tenantOf(req: Request, res: Response): string | null {
  const tenantId = (req as Request & { user?: { tenantId?: unknown } }).user?.tenantId;
  if (typeof tenantId !== "string" || tenantId.length === 0) {
    res.status(401).json({ error: "Authentication required" });
    return null;
  }
  return tenantId;
}

export function toDates<T extends Record<string, unknown>>(value: T, dateFields: string[]): T {
  const out: Record<string, unknown> = { ...value };
  for (const field of dateFields) {
    if (typeof out[field] === "string") out[field] = new Date(out[field] as string);
  }
  return out as T;
}
`;
}

function appModule(model: AppModel, runId: string): string {
  const imports = model.entities.map((e) => `import { ${lowerFirst(e.name)}Router } from "./${fileBase(e.name)}.routes.js";`).join("\n");
  const mounts = model.entities.map((e) => `  app.use("/api/${resourcePath(e.name)}", ${lowerFirst(e.name)}Router);`).join("\n");
  return `${header(runId)}import express, { type RequestHandler } from "express";
${imports}

/**
 * Builds the API. The caller must supply authentication middleware that sets req.user.tenantId
 * from a verified session; the generated routes refuse requests without it.
 */
export function createApp(authenticate: RequestHandler) {
  const app = express();
  app.use(express.json({ limit: "100kb" }));
  app.use(authenticate);
${mounts}
  return app;
}
`;
}

function clientModule(model: AppModel, runId: string): string {
  const parts = model.entities.map((e) => {
    const shape = e.fields.map((f) => `  ${f.name}${f.required ? "" : "?"}: ${TS_TYPE[f.type]}${f.required ? "" : " | null"};`).join("\n");
    const p = resourcePath(e.name);
    return `export interface ${e.name} {
  id: string;
${shape}
  createdAt: string;
  updatedAt: string;
}

export const ${lowerFirst(e.name)}Api = {
  list: () => request<${e.name}[]>("/api/${p}"),
  get: (id: string) => request<${e.name}>(\`/api/${p}/\${encodeURIComponent(id)}\`),
  create: (input: Omit<${e.name}, "id" | "createdAt" | "updatedAt">) =>
    request<${e.name}>("/api/${p}", { method: "POST", body: JSON.stringify(input) }),
  update: (id: string, input: Partial<Omit<${e.name}, "id" | "createdAt" | "updatedAt">>) =>
    request<${e.name}>(\`/api/${p}/\${encodeURIComponent(id)}\`, { method: "PATCH", body: JSON.stringify(input) }),
  archive: (id: string) => request<void>(\`/api/${p}/\${encodeURIComponent(id)}\`, { method: "DELETE" }),
};`;
  });
  return `${header(runId)}async function request<T>(url: string, init: RequestInit = {}): Promise<T> {
  const res = await fetch(url, { credentials: "include", headers: { "Content-Type": "application/json" }, ...init });
  if (!res.ok) throw new Error(\`Request failed with status \${res.status}\`);
  if (res.status === 204) return undefined as T;
  const body = await res.json();
  return body.data as T;
}

${parts.join("\n\n")}
`;
}

function sampleValue(type: AppFieldType): string {
  switch (type) {
    case "string": case "text": return `"value"`;
    case "integer": return "1";
    case "number": return "1.5";
    case "boolean": return "true";
    case "datetime": return `"2026-01-01T00:00:00.000Z"`;
  }
}
function wrongValue(type: AppFieldType): string {
  return type === "boolean" ? `"yes"` : type === "integer" || type === "number" ? `"not-a-number"` : "42";
}

function testModule(e: AppModelEntity, runId: string): string {
  const base = fileBase(e.name);
  const valid = e.fields.filter((f) => f.required).map((f) => `${f.name}: ${sampleValue(f.type)}`).join(", ");
  const firstRequired = e.fields.find((f) => f.required);
  const first = e.fields[0];
  return `${header(runId)}import { describe, it, expect } from "vitest";
import { parse${e.name}Create, parse${e.name}Update } from "../server/${base}.validation.js";

describe("${e.name} input validation", () => {
  it("accepts a payload with every required field", () => {
    expect(parse${e.name}Create({ ${valid} }).ok).toBe(true);
  });

  it("rejects platform-owned and unknown fields", () => {
    const result = parse${e.name}Create({ ${valid}${valid ? ", " : ""}tenantId: "other-tenant", isAdmin: true });
    expect(result.ok).toBe(false);
  });
${firstRequired ? `
  it("requires ${firstRequired.name} on create", () => {
    const result = parse${e.name}Create({});
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.errors).toContain("${firstRequired.name} is required");
  });
` : ""}
  it("rejects a wrongly typed ${first.name}", () => {
    expect(parse${e.name}Update({ ${first.name}: ${wrongValue(first.type)} }).ok).toBe(false);
  });

  it("rejects an empty update", () => {
    expect(parse${e.name}Update({}).ok).toBe(false);
  });
});
`;
}

function readme(model: AppModel, runId: string, mode: string): string {
  return `<!-- ${GENERATED_MARKER} run:${runId} -->
# ${model.applicationName}

Generated by ForgeStudio (${mode === "AI_PROVIDER" ? "AI-planned model" : "approved template"}).

What was checked: the source was syntax-checked and its relative imports resolve.
What was NOT done: no install, build, database migration, test execution or deployment.

Entities: ${model.entities.map((e) => e.name).join(", ")}.
Apply \`prisma/schema.sql\` (or the Prisma schema) to a development database only after review.
`;
}

export function emitApplicationSource(model: AppModel, spec: unknown, runId: string, mode: string): EmittedFile[] {
  const files: EmittedFile[] = [
    { path: "prisma/schema.prisma", content: prismaSchema(model, runId), role: "SCHEMA" },
    { path: "prisma/schema.sql", content: sqlPlan(model, runId), role: "SCHEMA" },
    {
      path: "server/db.ts",
      content: `${header(runId)}import { PrismaClient } from "@prisma/client";\n\nexport const db = new PrismaClient();\n`,
      role: "SERVER",
    },
    { path: "server/http.ts", content: httpModule(runId), role: "SERVER" },
    { path: "server/app.ts", content: appModule(model, runId), role: "SERVER" },
    { path: "client/api.ts", content: clientModule(model, runId), role: "CLIENT" },
    { path: "application-spec.json", content: JSON.stringify({ [GENERATED_MARKER]: runId, ...(spec as object) }, null, 2) + "\n", role: "SPEC" },
    { path: "README.md", content: readme(model, runId, mode), role: "DOC" },
  ];
  for (const e of model.entities) {
    files.push({ path: `server/${fileBase(e.name)}.validation.ts`, content: validationModule(e, runId), role: "VALIDATION" });
    files.push({ path: `server/${fileBase(e.name)}.routes.ts`, content: routesModule(e, runId), role: "SERVER" });
    files.push({ path: `tests/${fileBase(e.name)}.validation.test.ts`, content: testModule(e, runId), role: "TEST" });
  }
  return files.map((f) => ({ ...f, path: `${GENERATED_ROOT}/${f.path}` }));
}

export interface SourceValidation {
  ok: boolean;
  errors: string[];
  checkedFiles: number;
}

/** Static checks only: TypeScript syntax (esbuild), relative import resolution and JSON structure. */
export function validateEmittedSource(files: EmittedFile[]): SourceValidation {
  const errors: string[] = [];
  const paths = new Set(files.map((f) => f.path));
  let checkedFiles = 0;

  for (const file of files) {
    if (file.path.endsWith(".ts")) {
      checkedFiles++;
      let js: string;
      try {
        js = transformSync(file.content, { loader: "ts", format: "esm", sourcefile: file.path }).code;
      } catch (err: any) {
        const messages = Array.isArray(err?.errors) && err.errors.length > 0
          ? err.errors.map((e: any) => `${e.text}${e.location ? ` (line ${e.location.line})` : ""}`)
          : [String(err?.message || err)];
        for (const m of messages) errors.push(`${file.path}: ${m}`);
        continue;
      }
      // esbuild drops type-only imports, so imports are read from the TypeScript source text as
      // well: every relative module specifier must resolve to a generated file.
      const program = parseJs(js, { ecmaVersion: "latest", sourceType: "module" }) as any;
      const specifiers = new Set<string>();
      for (const node of program.body) {
        if (node.type === "ImportDeclaration" || ((node.type === "ExportNamedDeclaration" || node.type === "ExportAllDeclaration") && node.source)) {
          specifiers.add(node.source.value);
        }
      }
      for (const m of file.content.matchAll(/^\s*import\s+type\s[^;]*?from\s+["']([^"']+)["']/gm)) specifiers.add(m[1]);
      for (const spec of specifiers) {
        if (!spec.startsWith(".")) continue;
        const target = path.posix.normalize(path.posix.join(path.posix.dirname(file.path), spec)).replace(/\.js$/, ".ts");
        if (!paths.has(target)) errors.push(`${file.path}: import "${spec}" does not resolve within the generated source`);
      }
    } else if (file.path.endsWith(".json")) {
      checkedFiles++;
      try { JSON.parse(file.content); } catch { errors.push(`${file.path}: invalid JSON`); }
    } else if (file.path.endsWith(".prisma")) {
      checkedFiles++;
      const opens = (file.content.match(/{/g) || []).length;
      const closes = (file.content.match(/}/g) || []).length;
      if (opens !== closes) errors.push(`${file.path}: unbalanced braces`);
    }
  }
  return { ok: errors.length === 0, errors, checkedFiles };
}
