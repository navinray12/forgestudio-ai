const MIGRATE_MODULE = `import crypto from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { pool } from "./db.js";

const MIGRATIONS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "migrations");
const LOCK = "SELECT pg_advisory_lock(hashtext('app_schema_migrations'))";
const UNLOCK = "SELECT pg_advisory_unlock(hashtext('app_schema_migrations'))";

/** Applies pending migrations in order, each atomically, and refuses on checksum drift. */
async function main(): Promise<void> {
  const client = await pool.connect();
  try {
    await client.query(LOCK);
    await client.query(\`CREATE TABLE IF NOT EXISTS "app_schema_migrations" ("name" TEXT PRIMARY KEY, "checksum" TEXT NOT NULL, "appliedAt" TIMESTAMPTZ NOT NULL DEFAULT now())\`);
    const applied = new Map<string, string>(
      (await client.query(\`SELECT "name", "checksum" FROM "app_schema_migrations"\`)).rows.map((r) => [r.name, r.checksum]),
    );
    const files = (await readdir(MIGRATIONS)).filter((f) => f.endsWith(".sql")).sort();
    const missing = [...applied.keys()].filter((name) => !files.includes(name));
    if (missing.length) throw new Error(\`Applied migrations are missing from source: \${missing.join(", ")}\`);
    for (const file of files) {
      const sql = await readFile(path.join(MIGRATIONS, file), "utf8");
      const checksum = crypto.createHash("sha256").update(sql).digest("hex");
      const recorded = applied.get(file);
      if (recorded) {
        if (recorded !== checksum) throw new Error(\`Migration \${file} changed after it was applied (checksum drift)\`);
        continue;
      }
      await client.query("BEGIN");
      try {
        await client.query(sql);
        await client.query(\`INSERT INTO "app_schema_migrations" ("name", "checksum") VALUES ($1, $2)\`, [file, checksum]);
        await client.query("COMMIT");
        console.log(\`applied \${file}\`);
      } catch (err) {
        await client.query("ROLLBACK");
        throw err;
      }
    }
  } finally {
    await client.query(UNLOCK).catch(() => undefined);
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
`;

