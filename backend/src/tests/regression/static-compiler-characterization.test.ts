/**
 * Static HTML compiler characterization (services/destinations/staticCompiler.ts).
 *
 * Pins the COMPLETE output of compileCanonicalToStaticBundle (every file's path, content byte for byte,
 * size and content type, plus the bundle totals) for:
 *  - every element type handled by renderElementToHtml, in three variants each (minimal; rich, with
 *    every property the type reads, values containing & < > " ' and nested item arrays; alternate, with
 *    empty arrays, false flags, page: and javascript: links), from static-compiler.fixtures.json, which
 *    was generated from the unmodified compiler;
 *  - hand-written cases: recursion through containers / columns / WooCommerce builders / unknown types,
 *    flex / grid / masonry layouts, malformed and null elements, header / footer site parts with theme
 *    conditions, 404 / archive / search templates, SEO / robots / structured data, custom head
 *    sanitization, tokens, global styles and design tokens;
 *  - the exported helpers sanitizeCustomHead and resolveStaticHtmlHref.
 * static-compiler.golden.json was captured once from the unmodified compiler (before it was split into
 * services/destinations/staticHtml/) and is never regenerated by this test. Nothing is normalized.
 *
 * File contents are stored once in the golden's "blobs" (keyed by SHA-256; styles.css and runtime.js repeat
 * across cases); each actual file is compared with the stored content exactly, then by its hash.
 *
 * Determinism: the only clock read (bundle generatedAt) runs under a fixed system time.
 * config/prisma is replaced by a stub that throws on any use: the compile path is pure.
 */
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { describe, expect, it, vi, beforeAll, afterAll } from "vitest";

vi.mock("../../config/prisma.js", () => {
  const deny = new Proxy({}, { get(_t, key) { if (key === "then") return undefined; throw new Error(`database accessed: ${String(key)}`); } });
  return { prisma: deny, pgPool: deny };
});

const compiler = await import("../../services/destinations/staticCompiler.js");
const { compileCanonicalToStaticBundle, sanitizeCustomHead, resolveStaticHtmlHref } = compiler;

import { CASES, FIXED_NOW, HEADS, HREFS, fixtures } from "./static-compiler.cases.js";

const golden: Record<string, unknown> = JSON.parse(readFileSync(new URL("./static-compiler.golden.json", import.meta.url), "utf8"));

const blobs = golden.blobs as Record<string, string>;
const sha256 = (c: string) => createHash("sha256").update(c, "utf8").digest("hex");

/** The bundle with each file's content replaced by its SHA-256; the content itself must equal the stored one. */
function compileCase(name: string) {
  const bundle = JSON.parse(JSON.stringify(compileCanonicalToStaticBundle("site-1", 3, CASES[name]())));
  for (const f of bundle.files) {
    const h = sha256(f.content);
    expect(blobs[h], `${name}: ${f.path} content differs from every golden file`).toBe(f.content);
    f.content = `sha256:${h}`;
  }
  return bundle;
}

describe("static compiler: full bundle output", () => {
  beforeAll(() => { vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(FIXED_NOW); });
  afterAll(() => { vi.useRealTimers(); });

  it("the golden covers every case and every element fixture", () => {
    expect(Object.keys(golden).filter((k) => k.startsWith("bundle:")).sort()).toEqual(Object.keys(CASES).map((k) => `bundle:${k}`).sort());
    expect((fixtures.elements as any[]).length).toBe(fixtures.clauses.reduce((a: number, c: any) => a + c.labels.length, 0) * 3);
  });

  it.each(Object.keys(CASES))("%s", (name) => {
    expect(compileCase(name)).toEqual(golden[`bundle:${name}`]);
  });
});

describe("static compiler: exported helpers", () => {
  it("sanitizeCustomHead", () => {
    expect(HEADS.map((h) => sanitizeCustomHead(h as any))).toEqual(golden["helpers:sanitizeCustomHead"]);
  });
  it("resolveStaticHtmlHref", () => {
    expect(HREFS.map(([h, p]) => resolveStaticHtmlHref(h, p))).toEqual(golden["helpers:resolveStaticHtmlHref"]);
  });
  it("exports exactly the same public API", () => {
    expect(Object.keys(compiler).sort()).toEqual(golden["exports"]);
  });
});
