// @vitest-environment jsdom
/* global describe, it, expect, beforeAll, afterAll, vi -- vitest globals (globals: true); declared for `eslint .` */
/**
 * forgeProjectService characterization: the exported object keeps the same 275 methods in the same
 * order, and every method sends the same requests (URL under API_BASE, method, headers incl. the Bearer
 * token, body) and returns / throws the same values under six scripted responses (see serviceRecorder.ts).
 * forgeProjectService.golden.json was captured once from the unmodified service (before it was split into
 * domain modules) and is never regenerated by this test. crypto.randomUUID is pinned for determinism.
 */
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";
import { readFileSync } from "node:fs";
import { forgeProjectService } from "../../src/features/developer-workspace/services/forgeProjectService";
import { recordService, type MemberSpec } from "./serviceRecorder";

const here = dirname(fileURLToPath(import.meta.url));

const members: MemberSpec[] = JSON.parse(readFileSync(join(here, "forgeProjectService.members.json"), "utf8"));
const golden: Record<string, unknown> = JSON.parse(readFileSync(join(here, "forgeProjectService.golden.json"), "utf8"));

describe("forgeProjectService", () => {
  let recorded: Record<string, unknown> = {};
  beforeAll(async () => {
    localStorage.setItem("token", "tok-1");
    vi.spyOn(crypto, "randomUUID").mockReturnValue("00000000-0000-4000-8000-000000000001");
    recorded = await recordService(forgeProjectService as unknown as Record<string, unknown>, members);
  }, 240_000);
  afterAll(() => vi.restoreAllMocks());

  it("exposes the same methods in the same order", () => {
    expect(Object.keys(forgeProjectService)).toEqual(members.map((m) => m.name));
    for (const m of members) expect(typeof (forgeProjectService as any)[m.name]).toBe("function");
  });

  it("the golden covers every method", () => {
    expect(Object.keys(golden)).toEqual(members.map((m) => m.name));
  });

  it.each(members.map((m) => m.name))("%s: requests, results and side effects unchanged", (name) => {
    expect(recorded[name]).toEqual(golden[name]);
  });
});
